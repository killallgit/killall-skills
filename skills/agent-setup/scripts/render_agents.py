#!/usr/bin/env python3
"""Write the orchestrate skill and the builder, reviewer, and hall-monitor agents into a repository, or remove them.

Each agent template in templates/ becomes one agent file per host: .claude/agents/,
.codex/agents/, and .cursor/agents/. The orchestrate template becomes one skill per
host, because the main session runs it: a subagent cannot start further subagents.
The instruction block is written between markers in each instruction file a chosen
host reads. Everything written carries the agent-setup marker, and --remove deletes
only what carries it.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATES = ROOT / "templates"
AGENT_TEMPLATES = ("builder", "reviewer", "hall-monitor")
SKILL_TEMPLATE = "orchestrate"
# Agents earlier versions wrote; install and remove both clear them.
LEGACY_AGENTS = ("orchestrator",)
BLOCK_TEMPLATE = TEMPLATES / "instructions-block.tmpl.md"
# host: (agents folder, agent file suffix, skills folder)
HOSTS = {
    "claude": (Path(".claude/agents"), ".md", Path(".claude/skills")),
    "cursor": (Path(".cursor/agents"), ".md", Path(".cursor/skills")),
    "codex": (Path(".codex/agents"), ".toml", Path(".agents/skills")),
}
REQUIRED = (
    "project",
    "framework_note",
    "implement_note",
    "conventions",
    "gate",
    "default_branch",
    "worktree_note",
)
OPTIONAL = ("gate_scopes", "review_note")
MARKER = "Generated by agent-setup."
BLOCK_START = "<!-- agent-setup:start -->"
BLOCK_END = "<!-- agent-setup:end -->"
BLOCK = re.compile(re.escape(BLOCK_START) + r".*?" + re.escape(BLOCK_END) + r"\n?", re.S)
# The optional leading space goes with the token, so an empty value leaves no double space.
TOKEN = re.compile(r"( ?)\{\{([a-z_]+)\}\}")
IMPORTS_AGENTS = re.compile(r"^@(\./)?AGENTS\.md\s*$", re.M)
INSTRUCTION_FILES = ("AGENTS.md", "CLAUDE.md")


def substitute(text: str, values: dict[str, str]) -> str:
    def replace(match: re.Match[str]) -> str:
        if match.group(2) not in values:
            raise SystemExit(f"missing value for {{{{{match.group(2)}}}}}")
        value = values[match.group(2)]
        return match.group(1) + value if value else ""

    return TOKEN.sub(replace, text)


def split_frontmatter(text: str) -> tuple[dict[str, str], str]:
    if not text.startswith("---\n"):
        raise SystemExit("template is missing frontmatter")
    end = text.index("\n---\n", 4)
    meta = {}
    for line in text[4:end].splitlines():
        key, _, value = line.partition(":")
        meta[key.strip()] = value.strip()
    return meta, text[end + 5 :].strip() + "\n"


def render(name: str, values: dict[str, str]) -> tuple[dict[str, str], str]:
    return split_frontmatter(substitute((TEMPLATES / f"{name}.tmpl.md").read_text(encoding="utf-8"), values))


def toml_literal(value: str) -> str:
    if "'''" in value:
        raise SystemExit("a value contains ''' and cannot be written as a TOML literal")
    return "'''\n" + value.strip() + "\n'''"


def agent_file(host: str, meta: dict[str, str], body: str) -> str:
    name, description = meta["name"], json.dumps(meta["description"], ensure_ascii=False)
    if host == "claude":
        skills = f"skills: {meta['claude_skills']}\n" if meta.get("claude_skills") else ""
        return f"---\nname: {name}\ndescription: {description}\ntools: {json.dumps(meta['claude_tools'])}\n{skills}---\n\n{body}"
    if host == "cursor":
        return f"---\nname: {name}\ndescription: {description}\nmodel: inherit\nreadonly: {meta['cursor_readonly']}\n---\n\n{body}"
    return (
        f"name = {json.dumps(name)}\n"
        f"description = {toml_literal(meta['description'])}\n"
        f"sandbox_mode = {json.dumps(meta['codex_sandbox'])}\n"
        f"developer_instructions = {toml_literal(body)}\n"
    )


def skill_file(meta: dict[str, str], body: str) -> str:
    description = json.dumps(meta["description"], ensure_ascii=False)
    return f"---\nname: {meta['name']}\ndescription: {description}\n---\n\n{body}"


def agent_path(dest: Path, host: str, name: str) -> Path:
    folder, suffix, _ = HOSTS[host]
    return dest / folder / f"{name}{suffix}"


def skill_path(dest: Path, host: str) -> Path:
    return dest / HOSTS[host][2] / SKILL_TEMPLATE / "SKILL.md"


def ours(path: Path) -> bool:
    return path.is_file() and MARKER in path.read_text(encoding="utf-8")


def foreign(path: Path) -> bool:
    return path.exists() and not ours(path)


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print(f"wrote {path}")


def delete(path: Path, dest: Path) -> None:
    """Delete a file agent-setup wrote, then each folder up to dest it leaves empty. Git tracks no empty folder."""
    if not ours(path):
        return
    path.unlink()
    print(f"removed {path}")
    folder = path.parent
    while folder != dest and not any(folder.iterdir()):
        folder.rmdir()
        folder = folder.parent


def write_block(path: Path, block: str) -> None:
    wrapped = f"{BLOCK_START}\n{block.strip()}\n{BLOCK_END}\n"
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    if BLOCK.search(text):
        text = BLOCK.sub(lambda _: wrapped, text, count=1)
    else:
        text = (text.rstrip() + "\n\n" if text.strip() else "") + wrapped
    path.write_text(text, encoding="utf-8")
    print(f"wrote agent-setup block in {path}")


def instruction_files(dest: Path, hosts: list[str], names: list[str] | None) -> list[Path]:
    """The files the chosen hosts read. Codex and Cursor read AGENTS.md; Claude Code reads CLAUDE.md only."""
    if names:
        return [dest / name for name in names]
    agents, claude = dest / "AGENTS.md", dest / "CLAUDE.md"
    files = []
    if set(hosts) - {"claude"}:
        files.append(agents)
    if "claude" in hosts:
        imports = claude.is_file() and IMPORTS_AGENTS.search(claude.read_text(encoding="utf-8"))
        files.append(agents if imports else claude)
    return list(dict.fromkeys(files))


def install(dest: Path, values: dict[str, str], hosts: list[str], instructions: list[Path], force: bool) -> None:
    targets = [agent_path(dest, host, name) for name in AGENT_TEMPLATES for host in hosts]
    targets += [skill_path(dest, host) for host in hosts]
    blocked = [str(path) for path in targets if foreign(path)]
    if blocked and not force:
        raise SystemExit("not written by agent-setup, rerun with --force to replace: " + ", ".join(blocked))
    for name in AGENT_TEMPLATES:
        meta, body = render(name, values)
        for host in hosts:
            write(agent_path(dest, host, name), agent_file(host, meta, body))
    meta, body = render(SKILL_TEMPLATE, values)
    for host in hosts:
        write(skill_path(dest, host), skill_file(meta, body))
    for host in HOSTS:
        for name in LEGACY_AGENTS:
            delete(agent_path(dest, host, name), dest)
    block = substitute(BLOCK_TEMPLATE.read_text(encoding="utf-8"), values)
    for path in instructions:
        write_block(path, block)


def files_with_block(dest: Path) -> list[Path]:
    found = subprocess.run(
        ["git", "-C", str(dest), "grep", "-l", "-F", "--untracked", "-e", BLOCK_START],
        capture_output=True,
        text=True,
    ).stdout.splitlines()
    candidates = [dest / name for name in INSTRUCTION_FILES] + [dest / name for name in found]
    return [path for path in dict.fromkeys(candidates) if path.is_file()]


def remove(dest: Path) -> None:
    for host in HOSTS:
        for name in AGENT_TEMPLATES + LEGACY_AGENTS:
            delete(agent_path(dest, host, name), dest)
        delete(skill_path(dest, host), dest)
    for path in files_with_block(dest):
        text = path.read_text(encoding="utf-8")
        if not BLOCK.search(text):
            continue
        text = re.sub(r"\n{3,}", "\n\n", BLOCK.sub("", text)).strip()
        if text:
            path.write_text(text + "\n", encoding="utf-8")
            print(f"removed agent-setup block from {path}")
        else:
            path.unlink()
            print(f"removed {path}, which held only the agent-setup block")


def load_vars(path: Path) -> dict[str, str]:
    data = json.loads(path.read_text(encoding="utf-8"))
    missing = [key for key in REQUIRED if not str(data.get(key, "")).strip()]
    if missing:
        raise SystemExit(f"vars missing {', '.join(missing)}")
    return {key: str(data.get(key, "")).strip() for key in REQUIRED + OPTIONAL}


def main() -> None:
    parser = argparse.ArgumentParser(description="Write or remove the agent-setup agents and orchestrate skill.")
    parser.add_argument("--dest", type=Path, required=True)
    parser.add_argument("--vars", type=Path, help="JSON file with the template values")
    parser.add_argument("--hosts", default="claude,codex,cursor", help="comma-separated: claude, codex, cursor")
    parser.add_argument(
        "--instructions",
        action="append",
        help="instruction file for the block, repeatable; default: AGENTS.md for codex and cursor, "
        "CLAUDE.md for claude unless it imports @AGENTS.md",
    )
    parser.add_argument("--force", action="store_true", help="replace agent and skill files agent-setup did not write")
    parser.add_argument("--remove", action="store_true", help="remove everything agent-setup wrote")
    args = parser.parse_args()
    dest = args.dest.resolve()
    if not (dest / ".git").exists():
        raise SystemExit(f"dest is not a git checkout: {dest}")
    if args.remove:
        remove(dest)
        return
    if not args.vars:
        raise SystemExit("--vars is required unless --remove is set")
    hosts = [host.strip() for host in args.hosts.split(",") if host.strip()]
    unknown = [host for host in hosts if host not in HOSTS]
    if unknown or not hosts:
        raise SystemExit(f"unknown hosts: {', '.join(unknown) or 'none given'}")
    install(dest, load_vars(args.vars), hosts, instruction_files(dest, hosts, args.instructions), args.force)


if __name__ == "__main__":
    main()
