"""Write or remove the agent-setup agents and the orchestrator a session starts as."""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
from collections.abc import Callable
from functools import partial
from pathlib import Path
from typing import NamedTuple

TEMPLATES = Path(__file__).resolve().parent.parent / "templates"
AGENT_TEMPLATES = ("builder", "reviewer", "hall-monitor")
ORCHESTRATOR = "orchestrator"
HOSTS = {"claude": ".claude/agents/{}.md", "cursor": ".cursor/agents/{}.md", "codex": ".codex/agents/{}.toml"}
CLAUDE_SETTINGS = Path(".claude/settings.json")
CODEX_CONFIG = Path(".codex/config.toml")
CURSOR_RULE = Path(".cursor/rules/orchestrator.mdc")
# Earlier versions wrote these; install and --remove both delete them when they carry the marker.
LEGACY_FILES = (Path(".codex/agents/orchestrator.toml"), Path(".cursor/agents/orchestrator.md")) + tuple(
    Path(folder) / "skills/orchestrate/SKILL.md" for folder in (".claude", ".agents", ".cursor")
)
REQUIRED = ("project", "conventions", "gate", "default_branch", "worktree_note")
OPTIONAL = ("gate_scopes",)
MARKER = "Generated by agent-setup."
# Old blocks name the `orchestrate` skill between markers on their own lines; any other match is a quoted example.
BLOCK = re.compile(r"\n*^<!-- agent-setup:start -->\n.*?^<!-- agent-setup:end -->$\n*", re.MULTILINE | re.DOTALL)
LEGACY_BLOCK_TEXT = "`orchestrate` skill"
TOML_BLOCK = re.compile(r"^# agent-setup:start\n.*?^# agent-setup:end\n\n?", re.MULTILINE | re.DOTALL)
# Skip comments and all string forms so quoted delimiters cannot hide real root settings.
TOML_LITERAL = re.compile(r"""#[^\n]*|'''.*?'''|\"\"\"(?:\\.|(?!\"\"\").)*\"\"\"|"(?:\\.|[^"\\\n])*"|'[^'\n]*'""", re.DOTALL)
TOML_SESSION_SETTINGS = re.compile(r"^[ \t]*['\"]?(?:developer_instructions|model|model_reasoning_effort)['\"]?\s*=\s*('''.*?'''|\"\"\".*?\"\"\"|[^\n]*)\n?" + f"|(?P<literal>{TOML_LITERAL.pattern})", re.MULTILINE | re.DOTALL)
# The optional leading space goes with the token, so an empty value leaves no double space.
TOKEN = re.compile(r"( ?)\{\{([a-z_]+)\}\}")

class Output(NamedTuple):
    path: Path
    update: Callable[[str | None], str]
    foreign: Callable[[str | None], bool]


def substitute(text: str, values: dict[str, str]) -> str:
    def replace(match: re.Match[str]) -> str:
        value = values[match.group(2)]
        return match.group(1) + value if value else ""

    return TOKEN.sub(replace, text)


def render(name: str, values: dict[str, str]) -> tuple[dict[str, str], str]:
    text = substitute((TEMPLATES / f"{name}.tmpl.md").read_text(encoding="utf-8"), values)
    end = text.index("\n---\n", 4)
    meta = {key.strip(): value.strip() for key, _, value in (line.partition(":") for line in text[4:end].splitlines())}
    return meta, text[end + 5 :].strip() + "\n"


def toml_literal(value: str) -> str:
    if "'''" in value:
        raise SystemExit("a value contains ''' and cannot be written as a TOML literal")
    return "'''\n" + value.strip() + "\n'''"


def model_settings(host: str, meta: dict[str, str]) -> str:
    if host == "claude":
        return f"model: {meta['claude_model']}\neffort: {meta['claude_effort']}\n"
    return f"model = {json.dumps(meta['codex_model'])}\nmodel_reasoning_effort = {json.dumps(meta['codex_effort'])}\n"


def agent_file(host: str, meta: dict[str, str], body: str) -> str:
    name, description = meta["name"], json.dumps(meta["description"], ensure_ascii=False)
    if host == "claude":
        tools = f"tools: {json.dumps(meta['claude_tools'])}\n" if meta.get("claude_tools") else ""
        skills = f"skills: {meta['claude_skills']}\n" if meta.get("claude_skills") else ""
        return f"---\nname: {name}\ndescription: {description}\n{model_settings(host, meta)}{tools}{skills}---\n\n{body}"
    if host == "cursor":
        return f"---\nname: {name}\ndescription: {description}\nmodel: inherit\nreadonly: {meta['cursor_readonly']}\n---\n\n{body}"
    return f"name = {json.dumps(name)}\ndescription = {toml_literal(meta['description'])}\n{model_settings(host, meta)}developer_instructions = {toml_literal(body)}\n"


def agent_path(host: str, name: str) -> Path:
    return Path(HOSTS[host].format(name))


def whole_file(path: Path, content: str) -> Output:
    return Output(path, lambda _: content, lambda text: text is not None and MARKER not in text)


def load_settings(text: str | None) -> dict:
    try:
        return json.loads(text) if text and text.strip() else {}
    except json.JSONDecodeError as error:
        raise SystemExit(f"{CLAUDE_SETTINGS} is not valid JSON: {error}") from error


def with_agent(text: str | None) -> str:
    return json.dumps({**load_settings(text), "agent": ORCHESTRATOR}, indent=2, ensure_ascii=False) + "\n"


def without_agent(text: str) -> str:
    settings = load_settings(text)
    if settings.pop("agent", None) != ORCHESTRATOR:
        return text
    return json.dumps(settings, indent=2, ensure_ascii=False) + "\n" if settings else ""


def without_session_settings(text: str) -> str:
    """Drops our block and root session settings; settings inside a [table] are the user's."""
    text = TOML_BLOCK.sub("", text)
    blanked = TOML_LITERAL.sub(lambda match: re.sub(r"[^\n]", " ", match.group()), text)
    table = re.search(r"^[ \t]*\[", blanked, re.MULTILINE)
    cut = table.start() if table else len(text)
    return TOML_SESSION_SETTINGS.sub(lambda match: match["literal"] or "", text[:cut]) + text[cut:]


def with_toml_block(block: str, text: str | None) -> str:
    rest = without_session_settings(text or "")
    return block + ("\n" + rest if rest.strip() else "")


def without_instruction_block(text: str) -> str:
    stripped = BLOCK.sub(lambda match: "\n\n" if LEGACY_BLOCK_TEXT in match.group() else match.group(), text)
    if stripped == text:
        return text
    return stripped.strip() + "\n" if stripped.strip() else ""


def orchestrator_outputs(host: str, meta: dict[str, str], body: str) -> list[Output]:
    description = json.dumps(meta["description"], ensure_ascii=False)
    if host == "claude":
        other_agent = lambda text: load_settings(text).get("agent", ORCHESTRATOR) != ORCHESTRATOR
        return [whole_file(agent_path(host, ORCHESTRATOR), agent_file(host, meta, body)), Output(CLAUDE_SETTINGS, with_agent, other_agent)]
    if host == "cursor":
        return [whole_file(CURSOR_RULE, f"---\ndescription: {description}\nalwaysApply: true\n---\n\n{body}")]
    block = f"# agent-setup:start\n{model_settings(host, meta)}developer_instructions = {toml_literal(body)}\n# agent-setup:end\n"
    other_instructions = lambda text: without_session_settings(text or "") != TOML_BLOCK.sub("", text or "")
    return [Output(CODEX_CONFIG, partial(with_toml_block, block), other_instructions)]


def outputs(values: dict[str, str], hosts: list[str]) -> list[Output]:
    agents = {name: render(name, values) for name in AGENT_TEMPLATES}
    orchestrator = render(ORCHESTRATOR, values)
    found = []
    for host in hosts:
        found += [whole_file(agent_path(host, name), agent_file(host, *agents[name])) for name in AGENT_TEMPLATES]
        found += orchestrator_outputs(host, *orchestrator)
    return found


def read(path: Path) -> str | None:
    return path.read_text(encoding="utf-8") if path.is_file() else None


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print(f"wrote {path}")


def unlink(path: Path, dest: Path) -> None:
    """Also removes the folders this leaves empty, up to dest: git tracks no empty folder, so they would linger."""
    path.unlink()
    print(f"removed {path}")
    folder = path.parent
    while folder != dest and not any(folder.iterdir()):
        folder.rmdir()
        folder = folder.parent


def delete_ours(path: Path, dest: Path) -> None:
    if MARKER in (read(path) or ""):
        unlink(path, dest)


def strip_file(path: Path, strip: Callable[[str], str], dest: Path) -> None:
    current = read(path)
    stripped = None if current is None else strip(current)
    if stripped is None or stripped == current:
        return
    if stripped.strip():
        write(path, stripped)
    else:
        unlink(path, dest)


def clear_legacy(dest: Path) -> None:
    for path in LEGACY_FILES:
        delete_ours(dest / path, dest)
    grep = ["git", "-C", str(dest), "grep", "-l", "-F", "--untracked", "-e", "<!-- agent-setup:start -->"]
    found = subprocess.run(grep, check=False, capture_output=True, text=True).stdout.splitlines()
    # git grep skips ignored files, and earlier versions wrote these two whether git ignored them or not.
    for name in dict.fromkeys(["AGENTS.md", "CLAUDE.md", *found]):
        strip_file(dest / name, without_instruction_block, dest)


def project_state(dest: Path) -> tuple[Path, Path]:
    listing = subprocess.check_output(["git", "-C", str(dest), "worktree", "list", "--porcelain", "-z"], text=True)
    root = Path(listing.split("\0", 1)[0].removeprefix("worktree ")).resolve()
    key = re.sub(r"[^A-Za-z0-9]", "-", str(root))
    config = Path(os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config")
    config = config if config.is_absolute() else Path.home() / ".config"
    return root, config / "killall-skills/agents/state" / key


def exclude_path(dest: Path) -> Path:
    return (dest / subprocess.check_output(["git", "-C", str(dest), "rev-parse", "--git-path", "info/exclude"], text=True).strip()).resolve()


def install(dest: Path, values: dict[str, str], hosts: list[str], force: bool) -> None:
    root, state = project_state(dest)
    values = {**values, "state_dir": f"~/{state.relative_to(Path.home())}" if state.is_relative_to(Path.home()) else str(state)}
    generated = outputs(values, hosts)
    identity = f"Repository: {json.dumps(str(root), ensure_ascii=False)}\n"
    current = read(state / "README.md")
    if current and MARKER in current and not current.startswith(identity):
        raise SystemExit(f"state path belongs to another repository: {state}")
    guide = whole_file(state / "README.md", identity + (TEMPLATES / "state.md").read_text(encoding="utf-8"))
    ignored = {output.path for output in generated}
    local_excludes = exclude_path(dest)
    previous = TOML_BLOCK.search(read(local_excludes) or "")
    if previous:
        ignored.update(Path(line[1:]) for line in previous.group().splitlines() if line.startswith("/"))
    block = "# agent-setup:start\n" + "".join(f"/{path.as_posix()}\n" for path in sorted(ignored)) + "# agent-setup:end\n"
    exclusions = Output(local_excludes, lambda text: TOML_BLOCK.sub("", text or "") + ("" if not text or text.endswith("\n") else "\n") + block, lambda _: False)
    planned = [(dest / output.path, output) for output in [*generated, guide, exclusions]]
    blocked = [str(path) for path, output in planned if output.foreign(read(path))]
    if blocked and not force:
        raise SystemExit("not written by agent-setup, rerun with --force to replace: " + ", ".join(blocked))
    state.mkdir(parents=True, exist_ok=True, mode=0o700)
    for path, output in planned:
        current = read(path)
        updated = output.update(current)
        if updated != current:
            write(path, updated)
    clear_legacy(dest)


def remove(dest: Path) -> None:
    owned = [agent_path(host, name) for host in HOSTS for name in (*AGENT_TEMPLATES, ORCHESTRATOR)]
    for path in (*owned, CURSOR_RULE):
        delete_ours(dest / path, dest)
    strip_file(dest / CLAUDE_SETTINGS, without_agent, dest)
    strip_file(dest / CODEX_CONFIG, lambda text: TOML_BLOCK.sub("", text), dest)
    path = exclude_path(dest)
    strip_file(path, lambda text: TOML_BLOCK.sub("", text), path.parent)
    clear_legacy(dest)


def load_vars(path: Path) -> dict[str, str]:
    data = json.loads(path.read_text(encoding="utf-8"))
    missing = [key for key in REQUIRED if not str(data.get(key) or "").strip()]
    if missing:
        raise SystemExit(f"vars missing {', '.join(missing)}")
    return {key: str(data.get(key) or "").strip() for key in REQUIRED + OPTIONAL}


def main() -> None:
    parser = argparse.ArgumentParser(description="Write or remove the agent-setup agents and orchestrator.")
    parser.add_argument("--dest", type=Path, required=True)
    parser.add_argument("--vars", type=Path, help="JSON file with the template values")
    parser.add_argument("--hosts", default="claude,codex,cursor", help="comma-separated: claude, codex, cursor")
    parser.add_argument("--force", action="store_true", help="replace files and settings agent-setup did not write")
    parser.add_argument("--remove", action="store_true", help="remove generated agents and settings; preserve work state")
    args = parser.parse_args()
    dest = args.dest.resolve()
    if not (dest / ".git").exists():
        raise SystemExit(f"dest is not a git checkout: {dest}")
    if args.remove:
        remove(dest)
        return
    if not args.vars:
        raise SystemExit("--vars is required unless --remove is set")
    hosts = [host.strip() for host in args.hosts.split(",") if host.strip()]
    unknown = [host for host in hosts if host not in HOSTS]
    if unknown or not hosts:
        raise SystemExit(f"unknown hosts: {', '.join(unknown) or 'none given'}")
    install(dest, load_vars(args.vars), hosts, args.force)


if __name__ == "__main__":
    main()
