#!/usr/bin/env python3
"""Write or remove the agent-setup agents and the orchestrator a session starts as."""

from __future__ import annotations

import argparse
import json
import re
import subprocess
from collections.abc import Callable
from functools import partial
from pathlib import Path
from typing import NamedTuple

TEMPLATES = Path(__file__).resolve().parent.parent / "templates"
AGENT_TEMPLATES = ("builder", "reviewer", "hall-monitor")
ORCHESTRATOR = "orchestrator"
# host: (agents folder, agent file suffix)
HOSTS = {
    "claude": (Path(".claude/agents"), ".md"),
    "cursor": (Path(".cursor/agents"), ".md"),
    "codex": (Path(".codex/agents"), ".toml"),
}
CLAUDE_SETTINGS = Path(".claude/settings.json")
CODEX_CONFIG = Path(".codex/config.toml")
CURSOR_RULE = Path(".cursor/rules/orchestrator.mdc")
# Files earlier versions wrote that this one does not.
LEGACY_FILES = (Path(".codex/agents/orchestrator.toml"), Path(".cursor/agents/orchestrator.md")) + tuple(
    Path(folder) / "skills/orchestrate/SKILL.md" for folder in (".claude", ".agents", ".cursor")
)
REQUIRED = ("project", "conventions", "gate", "default_branch", "worktree_note")
OPTIONAL = ("gate_scopes",)
MARKER = "Generated by agent-setup."
BLOCK_START = "<!-- agent-setup:start -->"
BLOCK = re.compile(re.escape(BLOCK_START) + r".*?<!-- agent-setup:end -->\n?", re.DOTALL)
TOML_BLOCK = re.compile(r"# agent-setup:start\n.*?# agent-setup:end\n\n?", re.DOTALL)
TOML_INSTRUCTIONS = re.compile(r"^developer_instructions\s*=\s*('''.*?'''|\"\"\".*?\"\"\"|[^\n]*)\n?", re.MULTILINE | re.DOTALL)
# The optional leading space goes with the token, so an empty value leaves no double space.
TOKEN = re.compile(r"( ?)\{\{([a-z_]+)\}\}")
INSTRUCTION_FILES = ("AGENTS.md", "CLAUDE.md")

class Output(NamedTuple):
    path: Path
    update: Callable[[str | None], str]
    foreign: Callable[[str | None], bool]


def substitute(text: str, values: dict[str, str]) -> str:
    def replace(match: re.Match[str]) -> str:
        if match.group(2) not in values:
            raise SystemExit(f"missing value for {{{{{match.group(2)}}}}}")
        value = values[match.group(2)]
        return match.group(1) + value if value else ""

    return TOKEN.sub(replace, text)


def render(name: str, values: dict[str, str]) -> tuple[dict[str, str], str]:
    text = substitute((TEMPLATES / f"{name}.tmpl.md").read_text(encoding="utf-8"), values)
    end = text.index("\n---\n", 4)
    meta = {key.strip(): value.strip() for key, _, value in (line.partition(":") for line in text[4:end].splitlines())}
    return meta, text[end + 5 :].strip() + "\n"


def toml_literal(value: str) -> str:
    if "'''" in value:
        raise SystemExit("a value contains ''' and cannot be written as a TOML literal")
    return "'''\n" + value.strip() + "\n'''"


def agent_file(host: str, meta: dict[str, str], body: str) -> str:
    name, description = meta["name"], json.dumps(meta["description"], ensure_ascii=False)
    if host == "claude":
        skills = f"skills: {meta['claude_skills']}\n" if meta.get("claude_skills") else ""
        return f"---\nname: {name}\ndescription: {description}\ntools: {json.dumps(meta['claude_tools'])}\n{skills}---\n\n{body}"
    if host == "cursor":
        return f"---\nname: {name}\ndescription: {description}\nmodel: inherit\nreadonly: {meta['cursor_readonly']}\n---\n\n{body}"
    return (
        f"name = {json.dumps(name)}\n"
        f"description = {toml_literal(meta['description'])}\n"
        f"sandbox_mode = {json.dumps(meta['codex_sandbox'])}\n"
        f"developer_instructions = {toml_literal(body)}\n"
    )


def agent_path(host: str, name: str) -> Path:
    folder, suffix = HOSTS[host]
    return folder / f"{name}{suffix}"


def not_ours(text: str | None) -> bool:
    return text is not None and MARKER not in text


def whole_file(path: Path, content: str) -> Output:
    return Output(path, lambda _: content, not_ours)


def load_settings(text: str | None) -> dict:
    try:
        return json.loads(text) if text and text.strip() else {}
    except json.JSONDecodeError as error:
        raise SystemExit(f"{CLAUDE_SETTINGS} is not valid JSON: {error}") from error


def with_agent(text: str | None) -> str:
    return json.dumps({**load_settings(text), "agent": ORCHESTRATOR}, indent=2) + "\n"


def without_agent(text: str) -> str:
    settings = load_settings(text)
    if settings.get("agent") != ORCHESTRATOR:
        return text
    kept = {key: value for key, value in settings.items() if key != "agent"}
    return json.dumps(kept, indent=2) + "\n" if kept else ""


def with_toml_block(block: str, text: str | None) -> str:
    rest = TOML_INSTRUCTIONS.sub("", TOML_BLOCK.sub("", text or ""))
    return block + ("\n" + rest if rest.strip() else "")


def without_instruction_block(text: str) -> str:
    rest = re.sub(r"\n{3,}", "\n\n", BLOCK.sub("", text)).strip()
    return rest + "\n" if rest else ""


def orchestrator_outputs(host: str, meta: dict[str, str], body: str) -> list[Output]:
    description = json.dumps(meta["description"], ensure_ascii=False)
    if host == "claude":
        agent = f"---\nname: {ORCHESTRATOR}\ndescription: {description}\n---\n\n{body}"
        other_agent = lambda text: load_settings(text).get("agent", ORCHESTRATOR) != ORCHESTRATOR
        return [whole_file(agent_path(host, ORCHESTRATOR), agent), Output(CLAUDE_SETTINGS, with_agent, other_agent)]
    if host == "cursor":
        return [whole_file(CURSOR_RULE, f"---\ndescription: {description}\nalwaysApply: true\n---\n\n{body}")]
    block = f"# agent-setup:start\ndeveloper_instructions = {toml_literal(body)}\n# agent-setup:end\n"
    other_instructions = lambda text: bool(TOML_INSTRUCTIONS.search(TOML_BLOCK.sub("", text or "")))
    return [Output(CODEX_CONFIG, partial(with_toml_block, block), other_instructions)]


def outputs(values: dict[str, str], hosts: list[str]) -> list[Output]:
    agents = {name: render(name, values) for name in AGENT_TEMPLATES}
    orchestrator = render(ORCHESTRATOR, values)
    found = []
    for host in hosts:
        found += [whole_file(agent_path(host, name), agent_file(host, *agents[name])) for name in AGENT_TEMPLATES]
        found += orchestrator_outputs(host, *orchestrator)
    return found


def read(path: Path) -> str | None:
    return path.read_text(encoding="utf-8") if path.is_file() else None


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print(f"wrote {path}")


def unlink(path: Path, dest: Path) -> None:
    """Delete a file, then each folder up to dest it leaves empty. Git tracks no empty folder."""
    path.unlink()
    print(f"removed {path}")
    folder = path.parent
    while folder != dest and not any(folder.iterdir()):
        folder.rmdir()
        folder = folder.parent


def delete_ours(path: Path, dest: Path) -> None:
    if path.is_file() and not not_ours(read(path)):
        unlink(path, dest)


def strip_file(path: Path, strip: Callable[[str], str], dest: Path) -> None:
    current = read(path)
    stripped = strip(current) if current is not None else current
    if stripped == current:
        return
    write(path, stripped) if stripped.strip() else unlink(path, dest)


def files_with_block(dest: Path) -> list[Path]:
    grep = ["git", "-C", str(dest), "grep", "-l", "-F", "--untracked", "-e", BLOCK_START]
    found = subprocess.run(grep, check=False, capture_output=True, text=True).stdout.splitlines()
    return list(dict.fromkeys(dest / name for name in (*INSTRUCTION_FILES, *found)))


def clear_legacy(dest: Path) -> None:
    for path in LEGACY_FILES:
        delete_ours(dest / path, dest)
    for path in files_with_block(dest):
        strip_file(path, without_instruction_block, dest)


def install(dest: Path, values: dict[str, str], hosts: list[str], force: bool) -> None:
    planned = [(dest / output.path, output) for output in outputs(values, hosts)]
    blocked = [str(path) for path, output in planned if output.foreign(read(path))]
    if blocked and not force:
        raise SystemExit("not written by agent-setup, rerun with --force to replace: " + ", ".join(blocked))
    for path, output in planned:
        current = read(path)
        if output.update(current) != current:
            write(path, output.update(current))
    clear_legacy(dest)


def remove(dest: Path) -> None:
    owned = [agent_path(host, name) for host in HOSTS for name in (*AGENT_TEMPLATES, ORCHESTRATOR)]
    for path in (*owned, CURSOR_RULE):
        delete_ours(dest / path, dest)
    strip_file(dest / CLAUDE_SETTINGS, without_agent, dest)
    strip_file(dest / CODEX_CONFIG, lambda text: TOML_BLOCK.sub("", text), dest)
    clear_legacy(dest)


def load_vars(path: Path) -> dict[str, str]:
    data = json.loads(path.read_text(encoding="utf-8"))
    missing = [key for key in REQUIRED if not str(data.get(key, "")).strip()]
    if missing:
        raise SystemExit(f"vars missing {', '.join(missing)}")
    return {key: str(data.get(key, "")).strip() for key in REQUIRED + OPTIONAL}


def main() -> None:
    parser = argparse.ArgumentParser(description="Write or remove the agent-setup agents and orchestrator.")
    parser.add_argument("--dest", type=Path, required=True)
    parser.add_argument("--vars", type=Path, help="JSON file with the template values")
    parser.add_argument("--hosts", default="claude,codex,cursor", help="comma-separated: claude, codex, cursor")
    parser.add_argument("--force", action="store_true", help="replace files and settings agent-setup did not write")
    parser.add_argument("--remove", action="store_true", help="remove everything agent-setup wrote")
    args = parser.parse_args()
    dest = args.dest.resolve()
    if not (dest / ".git").exists():
        raise SystemExit(f"dest is not a git checkout: {dest}")
    if args.remove:
        remove(dest)
        return
    if not args.vars:
        raise SystemExit("--vars is required unless --remove is set")
    hosts = [host.strip() for host in args.hosts.split(",") if host.strip()]
    unknown = [host for host in hosts if host not in HOSTS]
    if unknown or not hosts:
        raise SystemExit(f"unknown hosts: {', '.join(unknown) or 'none given'}")
    install(dest, load_vars(args.vars), hosts, args.force)


if __name__ == "__main__":
    main()
