#!/usr/bin/env python3
"""Remove what render_factory.py installed in a repository.

Reads .factory/manifest.json when it exists and also scans the fixed install
footprint, so a checkout that lost its manifest still uninstalls cleanly. A
host symlink is removed only when it points into .factory/agents/, and a
/factory skill copy only when it carries the factory-builder marker. Setup
changes recorded at install time are printed, not reverted: the caller reverts
the ones the user chose before running this. Factory branches and worktrees
are listed and left in place.
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
from pathlib import Path

MANIFEST = Path(".factory/manifest.json")
HOST_AGENT_DIRS = (Path(".claude/agents"), Path(".cursor/agents"), Path(".codex/agents"))
SKILL_PATHS = (
    Path(".agents/skills/factory/SKILL.md"),
    Path(".claude/skills/factory/SKILL.md"),
    Path(".cursor/skills/factory/SKILL.md"),
)
MARKER = "generated by factory-builder"
LINE_FILES = (Path(".gitignore"), Path(".worktreeinclude"))
LINE = ".factory/"


def ours_link(path: Path) -> bool:
    return path.is_symlink() and ".factory/agents/" in path.readlink().as_posix()


def ours_skill(path: Path) -> bool:
    return path.is_file() and not path.is_symlink() and MARKER in path.read_text(encoding="utf-8")


def git(dest: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(dest), *args], capture_output=True, text=True, check=False).stdout


def main() -> None:
    parser = argparse.ArgumentParser(description="Remove factory files from a repository.")
    parser.add_argument("--dest", type=Path, required=True)
    parser.add_argument("--dry-run", action="store_true", help="print what would be removed")
    parser.add_argument("--keep-state", action="store_true", help="leave .factory/ in place")
    args = parser.parse_args()
    dest = args.dest.resolve()
    if not (dest / ".git").exists():
        raise SystemExit(f"dest is not a git checkout: {dest}")

    manifest_path = dest / MANIFEST
    manifest = json.loads(manifest_path.read_text(encoding="utf-8")) if manifest_path.exists() else {}
    if not manifest:
        print("no manifest; using the fixed install footprint")
    verb = "would remove" if args.dry_run else "removed"

    links = {dest / item for item in manifest.get("links", [])}
    for folder in HOST_AGENT_DIRS:
        if (dest / folder).is_dir():
            links |= {item for item in (dest / folder).iterdir() if item.is_symlink()}
    for link in sorted(links):
        if ours_link(link):
            if not args.dry_run:
                link.unlink()
            print(f"{verb} {link.relative_to(dest)}")

    skills = {dest / item for item in manifest.get("files", []) if not item.startswith(".factory/")}
    skills |= {dest / item for item in SKILL_PATHS}
    for skill in sorted(skills):
        if ours_skill(skill):
            if not args.dry_run:
                skill.unlink()
                if not any(skill.parent.iterdir()):
                    skill.parent.rmdir()
            print(f"{verb} {skill.relative_to(dest)}")

    created = {item["file"] for item in manifest.get("lines", []) if item.get("created")}
    for relative in LINE_FILES:
        path = dest / relative
        if not path.is_file():
            continue
        lines = path.read_text(encoding="utf-8").splitlines()
        kept = [line for line in lines if line.strip() != LINE]
        if len(kept) == len(lines):
            continue
        empty = not any(line.strip() for line in kept)
        if not args.dry_run:
            if empty and (relative.as_posix() in created or not manifest):
                path.unlink()
            else:
                path.write_text("".join(f"{line}\n" for line in kept), encoding="utf-8")
        print(f"{verb} {LINE} from {relative}")

    for item in manifest.get("setup", []):
        print(f"setup change, revert by hand if wanted: {item['change']} -> {item['revert']}")

    worktrees = [
        line.split(" ", 1)[1]
        for line in git(dest, "worktree", "list", "--porcelain").splitlines()
        if line.startswith("branch refs/heads/factory/")
    ]
    for branch in worktrees:
        print(f"left in place: worktree on {branch.removeprefix('refs/heads/')}")
    for branch in git(dest, "branch", "--list", "factory/*", "--format=%(refname:short)").split():
        print(f"left in place: branch {branch}")

    if not args.dry_run:
        for relative in (*HOST_AGENT_DIRS, Path(".agents/skills"), Path(".claude/skills"), Path(".cursor/skills"),
                         Path(".agents"), Path(".claude"), Path(".cursor"), Path(".codex")):
            folder = dest / relative
            if folder.is_dir() and not folder.is_symlink() and not any(folder.iterdir()):
                folder.rmdir()

    state = dest / ".factory"
    if state.exists() and not args.keep_state:
        if not args.dry_run:
            shutil.rmtree(state)
        print(f"{verb} .factory/")


if __name__ == "__main__":
    main()
